"""
Evaluation module for the Local AI Mock Interview Assistant.
Implements a 100% offline, deterministic, transparent rule-based scoring engine.
No external AI API, no remote network calls, no hallucinated scores.
"""

import re
from typing import Dict, Any, List, Tuple
from config import RUBRIC_WEIGHTS

STOP_WORDS = {
    "that", "this", "with", "from", "they", "them", "their", "what",
    "when", "where", "which", "have", "been", "were", "will", "would",
    "could", "should", "about", "over", "into", "some", "such", "only",
    "also", "more", "most", "than", "clear", "using", "your", "very"
}

def stem_word(w: str) -> str:
    """Lightweight deterministic stemmer for English suffixes."""
    w = w.lower()
    for suffix in ["ation", "tion", "ing", "ment", "ness", "able", "ible", "ies", "ied", "ed", "es", "s"]:
        if len(w) > len(suffix) + 3 and w.endswith(suffix):
            return w[:-len(suffix)]
    return w


class RuleBasedEvaluationEngine:
    """
    Transparent rule-based scoring engine that compares a candidate's answer
    against curated key concepts, domain keywords, structural signals, and relevance thresholds.
    """

    DISCLAIMER_TEXT = (
        "Note: This score is an automated estimate generated by a local rule-based engine "
        "(evaluating keyword presence, concept coverage, and structural elaboration). "
        "It is not generated by an external LLM or AI model."
    )

    # Common filler / low-effort phrases that indicate non-answers
    LOW_EFFORT_PHRASES = {
        "i don't know", "i dont know", "no idea", "not sure", "idk",
        "skip", "na", "n/a", "test", "asdf", "pass", "help", "nothing"
    }

    # Behavioral STAR markers
    STAR_PATTERNS = {
        "situation": [r"\bsituation\b", r"\bat (my|our)\b", r"\bwhen i was\b", r"\bin my previous\b", r"\bduring\b", r"\bwe were\b", r"\bcontext\b"],
        "task": [r"\btask\b", r"\bresponsibility\b", r"\bgoal\b", r"\bneeded to\b", r"\bhad to\b", r"\bobjective\b", r"\bchallenge\b"],
        "action": [r"\baction\b", r"\bi (implemented|built|led|decided|designed|proposed|created|investigated|scheduled|refactored|initiated|used)\b", r"\bmy approach\b", r"\bi resolved\b"],
        "result": [r"\bresult\b", r"\boutcome\b", r"\bas a result\b", r"\bultimately\b", r"\bin the end\b", r"\bimpact\b", r"\bimproved\b", r"\breduced\b", r"\bincreased\b"]
    }

    @classmethod
    def evaluate_answer(cls, question_data: Dict[str, Any], candidate_answer: str) -> Dict[str, Any]:
        """
        Evaluates a candidate's answer against a question definition.
        Returns a rich dictionary containing score out of 10, relevance,
        keywords found, missing concepts, strengths, and areas for improvement.
        """
        text = candidate_answer.strip()
        word_count = len(text.split()) if text else 0

        # Handle empty or trivial non-answers
        if not text or word_count < 3 or text.lower() in cls.LOW_EFFORT_PHRASES:
            return cls._generate_minimal_evaluation(question_data, word_count, reason="Empty or insufficient response")

        clean_lower = text.lower()

        # Check for immediate non-answer or spam pattern
        if any(clean_lower == phrase for phrase in cls.LOW_EFFORT_PHRASES):
            return cls._generate_minimal_evaluation(question_data, word_count, reason="Answer indicates no knowledge or skipped question")

        # 1. Evaluate Concept Coverage (Max: 3.5 points)
        concept_score, covered_concepts, missing_concepts = cls._evaluate_concepts(
            question_data.get("key_concepts", []),
            clean_lower
        )

        # 2. Evaluate Keyword Presence (Max: 2.5 points)
        keyword_score, keywords_found, keywords_missing = cls._evaluate_keywords(
            question_data.get("keywords", []),
            clean_lower
        )

        # 3. Evaluate Structural Quality & Completeness (Max: 2.0 points)
        structure_score, structure_feedback, star_coverage = cls._evaluate_structure(
            question_data.get("type", "technical"),
            clean_lower,
            word_count
        )

        # 4. Evaluate Relevance & Focus (Max: 2.0 points)
        relevance_score, relevance_level, relevance_pct = cls._evaluate_relevance(
            question_data,
            clean_lower,
            word_count,
            len(keywords_found),
            len(covered_concepts)
        )

        # Calculate final composite score (capped strictly at 0.0 - 10.0)
        raw_total = concept_score + keyword_score + structure_score + relevance_score
        final_score = round(max(0.0, min(10.0, raw_total)), 1)

        # Generate Strengths & Areas for Improvement
        strengths, improvements = cls._generate_feedback(
            question_data=question_data,
            final_score=final_score,
            word_count=word_count,
            covered_concepts=covered_concepts,
            missing_concepts=missing_concepts,
            keywords_found=keywords_found,
            keywords_missing=keywords_missing,
            star_coverage=star_coverage
        )

        return {
            "score": final_score,
            "max_score": 10.0,
            "relevance_level": relevance_level,
            "relevance_pct": relevance_pct,
            "keywords_found": keywords_found,
            "keywords_missing": keywords_missing,
            "concepts_covered": covered_concepts,
            "missing_concepts": missing_concepts,
            "strengths": strengths,
            "areas_for_improvement": improvements,
            "suggested_improved_answer": question_data.get("sample_answer", "No sample answer available."),
            "breakdown": {
                "concept_score": round(concept_score, 2),
                "keyword_score": round(keyword_score, 2),
                "structure_score": round(structure_score, 2),
                "relevance_score": round(relevance_score, 2)
            },
            "word_count": word_count,
            "disclaimer": cls.DISCLAIMER_TEXT
        }

    @classmethod
    def _evaluate_concepts(cls, key_concepts: List[str], text: str) -> Tuple[float, List[str], List[str]]:
        """
        Determines how many key concepts from the rubric are expressed in the answer.
        Uses lemma/stem matching across concept token clusters.
        """
        if not key_concepts:
            return RUBRIC_WEIGHTS["concept_coverage"], [], []

        # Tokenize text into stems
        text_words = set(re.findall(r"\b[a-zA-Z]{3,}\b", text))
        text_stems = {stem_word(w) for w in text_words}

        covered = []
        missing = []

        for concept in key_concepts:
            # Tokenize concept into significant terms
            concept_tokens = [
                w.lower() for w in re.findall(r"\b[a-zA-Z]{3,}\b", concept)
                if w.lower() not in STOP_WORDS
            ]
            if not concept_tokens:
                concept_tokens = [concept.lower()]

            concept_stems = [stem_word(w) for w in concept_tokens]

            # Check stem matches
            matches = sum(1 for cs in concept_stems if any(cs == ts or cs in ts or ts in cs for ts in text_stems))
            match_ratio = matches / len(concept_stems) if concept_stems else 0

            # A concept is covered if >= 2 stems match, or ratio >= 22%, or direct substring
            if concept.lower() in text or matches >= 2 or (matches >= 1 and len(concept_stems) <= 3) or match_ratio >= 0.22:
                covered.append(concept)
            else:
                missing.append(concept)

        ratio = len(covered) / len(key_concepts) if key_concepts else 1.0
        score = min(RUBRIC_WEIGHTS["concept_coverage"], ratio * RUBRIC_WEIGHTS["concept_coverage"])
        return score, covered, missing

    @classmethod
    def _evaluate_keywords(cls, target_keywords: List[str], text: str) -> Tuple[float, List[str], List[str]]:
        """
        Scans candidate text for presence of domain-specific keywords and acronyms.
        """
        if not target_keywords:
            return RUBRIC_WEIGHTS["keyword_match"], [], []

        text_words = set(re.findall(r"\b[a-zA-Z0-9_\-\+]{2,}\b", text))
        text_stems = {stem_word(w) for w in text_words}

        found = []
        missing = []

        for kw in target_keywords:
            kw_clean = kw.lower().strip()
            # If multi-word keyword (e.g. "global interpreter lock" or "code review")
            if " " in kw_clean:
                if kw_clean in text:
                    found.append(kw)
                    continue
                # Check if all component words appear
                parts = kw_clean.split()
                if all(stem_word(p) in text_stems for p in parts):
                    found.append(kw)
                    continue
            else:
                kw_stem = stem_word(kw_clean)
                pattern = r"\b" + re.escape(kw_clean) + r"\b"
                if re.search(pattern, text) or kw_stem in text_stems:
                    found.append(kw)
                    continue

            missing.append(kw)

        ratio = len(found) / len(target_keywords) if target_keywords else 1.0
        # Curve score so finding >= 60% of keywords gives top marks
        effective_ratio = min(1.0, ratio / 0.60)
        score = effective_ratio * RUBRIC_WEIGHTS["keyword_match"]
        return score, found, missing

    @classmethod
    def _evaluate_structure(cls, q_type: str, text: str, word_count: int) -> Tuple[float, List[str], Dict[str, bool]]:
        """
        Evaluates length, depth of elaboration, and structural framework (e.g. STAR for behavioral).
        """
        max_score = RUBRIC_WEIGHTS["structure_completeness"]
        star_coverage = {}
        feedback = []

        if q_type == "behavioral":
            # Check for STAR components
            for pillar, patterns in cls.STAR_PATTERNS.items():
                matched = any(re.search(pat, text) for pat in patterns)
                star_coverage[pillar] = matched

            star_points = sum(0.35 for val in star_coverage.values() if val)

            # Length bonus for thorough behavioral storytelling (ideal: 70 - 250 words)
            if word_count >= 120:
                length_points = 0.60
            elif word_count >= 70:
                length_points = 0.40
            elif word_count >= 40:
                length_points = 0.20
            else:
                length_points = 0.05

            score = min(max_score, star_points + length_points)
        else:
            # Technical structure: checks for elaboration, trade-offs, and examples
            score = 0.0
            if word_count >= 100:
                score += 1.0
            elif word_count >= 50:
                score += 0.7
            elif word_count >= 25:
                score += 0.4
            else:
                score += 0.1

            # Bonus for contrastive logic / trade-offs ("whereas", "however", "trade-off", "because", "for example")
            analytical_markers = [r"\bwhereas\b", r"\bhowever\b", r"\bbecause\b", r"\btrade-off\b", r"\bfor example\b", r"\bin contrast\b", r"\bunlike\b"]
            found_markers = sum(1 for p in analytical_markers if re.search(p, text))
            if found_markers >= 2:
                score += 0.6
            elif found_markers >= 1:
                score += 0.3

            # Bonus for code or architectural mentions
            if any(term in text for term in ["function", "class", "module", "api", "database", "memory", "cache", "server", "query"]):
                score += 0.4

            score = min(max_score, score)

        return score, feedback, star_coverage

    @classmethod
    def _evaluate_relevance(cls, question_data: Dict[str, Any], text: str, word_count: int, kw_count: int, concept_count: int) -> Tuple[float, str, int]:
        """
        Estimates topical relevance percentage and score.
        """
        max_score = RUBRIC_WEIGHTS["relevance_focus"]

        # Base relevance driven by detected keywords and concepts
        expected_kw_count = len(question_data.get("keywords", [])) or 1
        expected_concepts = len(question_data.get("key_concepts", [])) or 1

        kw_ratio = min(1.0, kw_count / max(1, expected_kw_count * 0.5))
        concept_ratio = min(1.0, concept_count / max(1, expected_concepts * 0.5))

        # Check question topic overlap
        topic = question_data.get("topic", "").lower()
        topic_match = 1.0 if any(stem_word(token) in text for token in topic.split() if len(token) > 3) else 0.4

        relevance_index = (kw_ratio * 0.45) + (concept_ratio * 0.40) + (topic_match * 0.15)

        # Scale to percentage
        relevance_pct = int(min(100, max(10, relevance_index * 100)))

        # Assign descriptor
        if relevance_pct >= 70:
            relevance_level = "High Relevance"
            score = max_score
        elif relevance_pct >= 45:
            relevance_level = "Moderate Relevance"
            score = max_score * 0.70
        elif relevance_pct >= 25:
            relevance_level = "Low Relevance"
            score = max_score * 0.35
        else:
            relevance_level = "Insufficient / Off-Topic"
            score = 0.1

        return score, relevance_level, relevance_pct

    @classmethod
    def _generate_feedback(
        cls,
        question_data: Dict[str, Any],
        final_score: float,
        word_count: int,
        covered_concepts: List[str],
        missing_concepts: List[str],
        keywords_found: List[str],
        keywords_missing: List[str],
        star_coverage: Dict[str, bool]
    ) -> Tuple[List[str], List[str]]:
        """
        Synthesizes transparent, human-readable strengths and actionable improvement tips.
        """
        strengths = []
        improvements = []
        q_type = question_data.get("type", "technical")

        # 1. Feedback on Concepts
        if covered_concepts:
            strengths.append(f"Demonstrated solid grasp of key concept(s): {', '.join(covered_concepts[:3])}.")
        if missing_concepts:
            improvements.append(f"Deepen coverage on missed topic(s): {', '.join(missing_concepts[:2])}.")

        # 2. Feedback on Vocabulary
        if keywords_found:
            strengths.append(f"Accurately incorporated domain terminology: {', '.join(keywords_found[:4])}.")
        if len(keywords_missing) > len(keywords_found):
            sample_kw = ', '.join(keywords_missing[:3])
            improvements.append(f"Boost technical precision by referencing industry terms such as: {sample_kw}.")

        # 3. Structural feedback
        if q_type == "behavioral":
            covered_star = [k.capitalize() for k, v in star_coverage.items() if v]
            missed_star = [k.capitalize() for k, v in star_coverage.items() if not v]
            if len(covered_star) >= 3:
                strengths.append(f"Strong adherence to the STAR narrative structure ({', '.join(covered_star)}).")
            if missed_star:
                improvements.append(f"Enhance behavioral storytelling by explicitly stating your {', '.join(missed_star)}.")
        else:
            if word_count < 45:
                improvements.append(f"Your answer is currently concise ({word_count} words). Aim for 60-120 words to elaborate on trade-offs and edge cases.")
            elif word_count >= 80:
                strengths.append("Provided a well-developed, thorough explanation with adequate technical depth.")

        # Ensure at least one supportive strength and actionable tip exist
        if not strengths:
            strengths.append("Attempted to address the question prompt with initial thoughts.")
        if not improvements:
            improvements.append("Outstanding coverage! For senior-level impact, highlight production metrics, latency benchmarks, or specific failure modes.")

        return strengths, improvements

    @classmethod
    def _generate_minimal_evaluation(cls, question_data: Dict[str, Any], word_count: int, reason: str) -> Dict[str, Any]:
        """
        Provides honest, zero/near-zero evaluation when candidate submits no content.
        """
        return {
            "score": 0.0,
            "max_score": 10.0,
            "relevance_level": "No Content / Skipped",
            "relevance_pct": 0,
            "keywords_found": [],
            "keywords_missing": question_data.get("keywords", [])[:5],
            "concepts_covered": [],
            "missing_concepts": question_data.get("key_concepts", [])[:3],
            "strengths": ["None identified for this submission."],
            "areas_for_improvement": [
                f"{reason}. Provide a complete answer explaining the core mechanisms and relevant experience.",
                "Review the suggested model response below to understand what interviewers expect."
            ],
            "suggested_improved_answer": question_data.get("sample_answer", "No sample answer available."),
            "breakdown": {
                "concept_score": 0.0,
                "keyword_score": 0.0,
                "structure_score": 0.0,
                "relevance_score": 0.0
            },
            "word_count": word_count,
            "disclaimer": cls.DISCLAIMER_TEXT
        }
