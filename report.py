"""
Report generation module for the Local AI Mock Interview Assistant.
Generates comprehensive reports in PDF, Markdown, and JSON formats.
100% offline, zero external API dependencies.
"""

import json
import os
from pathlib import Path
from typing import Dict, Any, List, Optional
from datetime import datetime
from config import REPORTS_DIR


def generate_markdown_report(summary: Dict[str, Any], questions_data: List[Dict[str, Any]]) -> str:
    """
    Generates a GitHub-flavored Markdown interview evaluation report.
    """
    created_at = summary.get("created_at", datetime.now().strftime("%Y-%m-%d %H:%M:%S"))
    total_score = summary.get("total_score", 0.0)
    max_score = summary.get("max_possible_score", 50.0)
    pct = summary.get("percentage", 0.0)
    grade = summary.get("grade", "N/A")
    role = summary.get("role", "General Role")
    level = summary.get("experience_level", "General Level")
    tech_avg = summary.get("tech_average", 0.0)
    beh_avg = summary.get("behavioral_average", 0.0)
    duration = summary.get("duration_seconds", 0)

    mins, secs = divmod(duration, 60)
    time_str = f"{mins}m {secs}s" if mins > 0 else f"{secs}s"

    lines = [
        f"# AI Mock Interview Performance Report",
        f"**Session ID:** `{summary.get('session_id', 'N/A')}`  ",
        f"**Date:** {created_at} | **Duration:** {time_str}  ",
        f"**Target Role:** {role}  ",
        f"**Experience Level:** {level}  ",
        "",
        "---",
        "",
        "## Executive Summary",
        "",
        "| Metric | Result |",
        "| :--- | :--- |",
        f"| **Overall Score** | **{total_score} / {max_score} ({pct}%)** |",
        f"| **Performance Tier** | {grade} |",
        f"| **Technical Average** | {tech_avg} / 10.0 |",
        f"| **Behavioral Average** | {beh_avg} / 10.0 |",
        f"| **Total Questions** | {len(questions_data)} |",
        "",
        "> **Transparency Notice:** Scores and feedback in this report were generated by a deterministic, local rule-based evaluation engine analyzing concept coverage, technical vocabulary, and structural clarity. No external AI APIs or remote services were used.",
        "",
        "---",
        "",
        "## Question-by-Question Breakdown",
        ""
    ]

    for idx, q in enumerate(questions_data, start=1):
        q_text = q.get("question_text") or q.get("question", "")
        q_type = q.get("question_type") or q.get("type", "technical")
        topic = q.get("topic", "General")
        score = q.get("score", 0.0)
        relevance = q.get("relevance_level", "N/A")
        relevance_pct = q.get("relevance_pct", 0)
        candidate_ans = q.get("candidate_answer") or q.get("user_answer", "*(No answer provided)*")
        kw_found = q.get("keywords_found", [])
        missing_concepts = q.get("missing_concepts", [])
        strengths = q.get("strengths", [])
        improvements = q.get("areas_for_improvement", [])
        suggested = q.get("suggested_answer") or q.get("suggested_improved_answer", "")

        lines.extend([
            f"### Question {idx}: {topic} ({q_type.capitalize()})",
            f"**Prompt:** *{q_text}*",
            "",
            f"- **Score:** `{score} / 10.0`",
            f"- **Relevance:** `{relevance} ({relevance_pct}%)`",
            f"- **Keywords Found:** {', '.join(kw_found) if kw_found else 'None detected'}",
            "",
            "#### Candidate Answer:",
            f"> {candidate_ans}",
            "",
            "#### Evaluation & Feedback:",
            "**Key Strengths:**"
        ])

        for s in strengths:
            lines.append(f"- {s}")

        lines.append("")
        lines.append("**Areas for Improvement:**")
        for imp in improvements:
            lines.append(f"- {imp}")

        if missing_concepts:
            lines.append("")
            lines.append(f"**Missing Core Concepts:** {', '.join(missing_concepts)}")

        lines.append("")
        lines.append("#### Recommended Model Response:")
        lines.append(f"```text\n{suggested}\n```")
        lines.append("")
        lines.append("---")
        lines.append("")

    lines.extend([
        "## Actionable Next Steps",
        "1. **Vocabulary Precision:** Review missing domain terminology highlighted in red/orange.",
        "2. **Trade-Off Articulation:** Elaborate on memory, latency, and scalability trade-offs in technical prompts.",
        "3. **STAR Method Consistency:** Ensure behavioral answers consistently state the specific Task, Actions taken, and quantitative Results.",
        "",
        "*Report generated locally by AI Mock Interview Assistant.*"
    ])

    return "\n".join(lines)


def generate_json_report(summary: Dict[str, Any], questions_data: List[Dict[str, Any]]) -> str:
    """
    Generates a structured, machine-readable JSON report.
    """
    report_dict = {
        "report_metadata": {
            "generator": "Local AI Mock Interview Assistant",
            "version": "2.0.0",
            "scoring_engine": "Rule-Based Deterministic Engine",
            "generated_at": datetime.now().isoformat()
        },
        "session_summary": summary,
        "questions_evaluation": questions_data
    }
    return json.dumps(report_dict, indent=2)


def generate_pdf_report(summary: Dict[str, Any], questions_data: List[Dict[str, Any]], output_path: Optional[str] = None) -> bytes:
    """
    Generates a styled, publication-ready PDF report.
    Uses ReportLab if installed; gracefully falls back to a clean pure-Python PDF builder.
    """
    try:
        from reportlab.lib.pagesizes import letter
        from reportlab.lib import colors
        from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
        from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
        from io import BytesIO

        buffer = BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=letter,
            rightMargin=36,
            leftMargin=36,
            topMargin=36,
            bottomMargin=36
        )

        styles = getSampleStyleSheet()

        # Custom styles
        title_style = ParagraphStyle(
            'ReportTitle',
            parent=styles['Heading1'],
            fontSize=22,
            leading=26,
            textColor=colors.HexColor('#1E293B'),
            fontName='Helvetica-Bold'
        )

        subtitle_style = ParagraphStyle(
            'ReportSubtitle',
            parent=styles['Normal'],
            fontSize=10,
            leading=14,
            textColor=colors.HexColor('#64748B'),
            fontName='Helvetica'
        )

        h2_style = ParagraphStyle(
            'SectionHeader',
            parent=styles['Heading2'],
            fontSize=14,
            leading=18,
            textColor=colors.HexColor('#2563EB'),
            fontName='Helvetica-Bold',
            spaceBefore=12,
            spaceAfter=6
        )

        body_style = ParagraphStyle(
            'ReportBody',
            parent=styles['Normal'],
            fontSize=9,
            leading=13,
            textColor=colors.HexColor('#334155'),
            fontName='Helvetica'
        )

        callout_style = ParagraphStyle(
            'Callout',
            parent=styles['Normal'],
            fontSize=8,
            leading=11,
            textColor=colors.HexColor('#475569'),
            fontName='Helvetica-Oblique'
        )

        story = []

        # Header Title
        story.append(Paragraph("AI Mock Interview Performance Report", title_style))
        story.append(Paragraph(f"Generated on {summary.get('created_at', '')} | 100% Local Rule-Based Engine", subtitle_style))
        story.append(Spacer(1, 10))
        story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor('#E2E8F0'), spaceAfter=12))

        # Executive Summary Table
        total_score = summary.get("total_score", 0.0)
        max_score = summary.get("max_possible_score", 50.0)
        pct = summary.get("percentage", 0.0)
        role = summary.get("role", "N/A")
        level = summary.get("experience_level", "N/A")
        grade = summary.get("grade", "N/A")

        summary_data = [
            [Paragraph("<b>Target Role:</b>", body_style), Paragraph(role, body_style),
             Paragraph("<b>Overall Score:</b>", body_style), Paragraph(f"<b>{total_score} / {max_score} ({pct}%)</b>", body_style)],
            [Paragraph("<b>Experience:</b>", body_style), Paragraph(level, body_style),
             Paragraph("<b>Performance Tier:</b>", body_style), Paragraph(grade, body_style)],
            [Paragraph("<b>Tech Average:</b>", body_style), Paragraph(f"{summary.get('tech_average', 0.0)} / 10.0", body_style),
             Paragraph("<b>Behavioral Average:</b>", body_style), Paragraph(f"{summary.get('behavioral_average', 0.0)} / 10.0", body_style)]
        ]

        summary_table = Table(summary_data, colWidths=[90, 180, 110, 160])
        summary_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#F8FAFC')),
            ('BOX', (0, 0), (-1, -1), 1, colors.HexColor('#CBD5E1')),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#E2E8F0')),
            ('TOPPADDING', (0, 0), (-1, -1), 5),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
            ('LEFTPADDING', (0, 0), (-1, -1), 6),
            ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ]))

        story.append(summary_table)
        story.append(Spacer(1, 14))

        # Disclaimer box
        story.append(Paragraph("<b>Notice:</b> This evaluation was conducted entirely offline using a transparent rule-based algorithm analyzing concept coverage and keyword presence. No external AI APIs or personal data transfers occurred.", callout_style))
        story.append(Spacer(1, 10))

        # Question details
        story.append(Paragraph("Detailed Question Breakdown", h2_style))

        for idx, q in enumerate(questions_data, start=1):
            q_topic = q.get("topic", "Question")
            q_type = (q.get("question_type") or q.get("type", "tech")).capitalize()
            q_score = q.get("score", 0.0)
            q_text = q.get("question_text") or q.get("question", "")
            ans = q.get("candidate_answer") or q.get("user_answer") or "*(No answer submitted)*"
            kw_found = ", ".join(q.get("keywords_found", [])) or "None"
            strengths_text = " • ".join(q.get("strengths", [])) or "None noted"
            improvements_text = " • ".join(q.get("areas_for_improvement", [])) or "None noted"

            # Clean for XML-safe paragraph
            safe_q_text = q_text.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
            safe_ans = ans.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
            safe_strengths = strengths_text.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
            safe_improvements = improvements_text.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')

            q_data_table = [
                [Paragraph(f"<b>Q{idx}: {q_topic} ({q_type})</b>", body_style), Paragraph(f"<b>Score: {q_score} / 10.0</b>", body_style)],
                [Paragraph(f"<i>Prompt:</i> {safe_q_text}", body_style), ""],
                [Paragraph(f"<b>Candidate Answer:</b> {safe_ans[:350]}...", body_style), ""],
                [Paragraph(f"<b>Keywords Detected:</b> {kw_found}", callout_style), ""],
                [Paragraph(f"<b>Strengths:</b> {safe_strengths}", body_style), ""],
                [Paragraph(f"<b>Areas to Improve:</b> {safe_improvements}", body_style), ""]
            ]

            q_table = Table(q_data_table, colWidths=[420, 120])
            q_table.setStyle(TableStyle([
                ('SPAN', (0, 1), (1, 1)),
                ('SPAN', (0, 2), (1, 2)),
                ('SPAN', (0, 3), (1, 3)),
                ('SPAN', (0, 4), (1, 4)),
                ('SPAN', (0, 5), (1, 5)),
                ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#EFF6FF')),
                ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor('#BFDBFE')),
                ('TOPPADDING', (0, 0), (-1, -1), 3),
                ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
                ('LEFTPADDING', (0, 0), (-1, -1), 5),
                ('RIGHTPADDING', (0, 0), (-1, -1), 5),
            ]))

            story.append(q_table)
            story.append(Spacer(1, 10))

        doc.build(story)
        pdf_bytes = buffer.getvalue()
        buffer.close()

    except Exception as e:
        # Graceful pure-Python PDF generator fallback
        pdf_bytes = _build_simple_fallback_pdf(summary, questions_data)

    if output_path:
        with open(output_path, "wb") as f:
            f.write(pdf_bytes)

    return pdf_bytes


def _build_simple_fallback_pdf(summary: Dict[str, Any], questions_data: List[Dict[str, Any]]) -> bytes:
    """
    Pure-Python fallback PDF generator conforming to PDF-1.4 specifications.
    Ensures PDF download works even if external libraries are not present.
    """
    text_lines = [
        "AI MOCK INTERVIEW PERFORMANCE REPORT",
        "=" * 48,
        f"Session: {summary.get('session_id', 'N/A')}",
        f"Date: {summary.get('created_at', '')}",
        f"Role: {summary.get('role', '')} ({summary.get('experience_level', '')})",
        f"Total Score: {summary.get('total_score', 0)} / {summary.get('max_possible_score', 50)} ({summary.get('percentage', 0)}%)",
        f"Performance Tier: {summary.get('grade', '')}",
        f"Tech Avg: {summary.get('tech_average', 0)} / 10 | Behavioral Avg: {summary.get('behavioral_average', 0)} / 10",
        "-" * 48,
        "QUESTION BREAKDOWN:"
    ]

    for idx, q in enumerate(questions_data, start=1):
        q_text = q.get('question_text') or q.get('question', '')
        score = q.get('score', 0.0)
        topic = q.get('topic', 'General')
        text_lines.append(f"Q{idx} [{topic}]: Score {score}/10")
        text_lines.append(f"Prompt: {q_text[:90]}")
        strengths = "; ".join(q.get('strengths', []))
        text_lines.append(f"Strengths: {strengths[:100]}")
        text_lines.append("-" * 35)

    text_lines.append("Note: Generated locally using rule-based scoring.")

    # Convert text_lines to PDF content stream
    stream_content = "BT\n/F1 9 Tf\n12 TL\n36 740 Td\n"
    for line in text_lines[:45]:
        safe_line = line.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")
        stream_content += f"({safe_line}) '\n"
    stream_content += "ET\n"

    stream_bytes = stream_content.encode("latin-1", errors="replace")
    stream_len = len(stream_bytes)

    pdf_body = (
        b"%PDF-1.4\n"
        b"1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n"
        b"2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n"
        b"3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>\nendobj\n"
        b"4 0 obj\n<< /Length " + str(stream_len).encode("ascii") + b" >>\nstream\n" +
        stream_bytes +
        b"\nendstream\nendobj\n"
        b"5 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj\n"
    )

    # Simple xref
    xref_offset = len(pdf_body)
    pdf_xref = (
        b"xref\n0 6\n"
        b"0000000000 65535 f \n"
        b"0000000009 00000 n \n"
        b"0000000056 00000 n \n"
        b"0000000111 00000 n \n"
        b"0000000234 00000 n \n"
        b"0000000350 00000 n \n"
        b"trailer\n<< /Size 6 /Root 1 0 R >>\n"
        b"startxref\n" + str(xref_offset).encode("ascii") + b"\n%%EOF\n"
    )

    return pdf_body + pdf_xref


def save_all_reports(summary: Dict[str, Any], questions_data: List[Dict[str, Any]]) -> Dict[str, str]:
    """
    Saves PDF, Markdown, and JSON files to the saved_reports directory.
    Returns a dictionary of paths.
    """
    sid = summary.get("session_id", "session")
    safe_sid = sid[:8]

    md_path = REPORTS_DIR / f"report_{safe_sid}.md"
    json_path = REPORTS_DIR / f"report_{safe_sid}.json"
    pdf_path = REPORTS_DIR / f"report_{safe_sid}.pdf"

    # Write Markdown
    md_content = generate_markdown_report(summary, questions_data)
    with open(md_path, "w", encoding="utf-8") as f:
        f.write(md_content)

    # Write JSON
    json_content = generate_json_report(summary, questions_data)
    with open(json_path, "w", encoding="utf-8") as f:
        f.write(json_content)

    # Write PDF
    generate_pdf_report(summary, questions_data, str(pdf_path))

    return {
        "markdown": str(md_path),
        "json": str(json_path),
        "pdf": str(pdf_path)
    }

